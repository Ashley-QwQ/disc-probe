def observer(nm):
    return np.stack([np.interp(nm, TABLE[:,0], TABLE[:,k]) for k in (1,2,3)], -1)


def illuminant(nm, name):
    if name == 'D65':
        return np.interp(nm, TABLE[:,0], TABLE[:,4])
    if name == 'LED':
        return np.exp(-.5*((nm-450)/12)**2) + .75*np.exp(-.5*((nm-560)/55)**2)
    raise ValueError(name)


def responses(step_nm=1.):
    nm = np.arange(380,780+step_nm/2,step_nm)
    cmf = observer(nm)
    quad = np.full(len(nm),step_nm)
    quad[[0,-1]] *= .5
    out, whites = [], {}
    for lamp in ('LED','D65'):
        spd = illuminant(nm,lamp)
        k = 1 / np.sum(spd*cmf[:,1]*quad)
        r = k*spd[:,None]*cmf*quad[:,None]
        out.append(r)
        white = r.sum(0)
        whites[lamp] = {'XYZ':white.tolist(),'xy':(white[:2]/white.sum()).tolist()}
    return nm/1000, np.concatenate(out,axis=1), whites
