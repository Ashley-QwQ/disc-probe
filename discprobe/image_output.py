"""Serialize ISO generation and consumption and retain the generation self-check."""

from contextlib import contextmanager
import json
import os
from pathlib import Path
from stat import S_ISREG
import tempfile

from . import iso9660
from .drive_lock import FileLocked, file_lock


@contextmanager
def exclusive(path):
    image = Path(path).resolve()
    try:
        with file_lock(Path(str(image) + '.lock')):
            yield image
    except FileLocked:
        raise ValueError('这个镜像路径正在使用。请等当前任务结束或换一个路径。 / '
                         'This image path is in use. Wait for the current task or choose another path.') from None


def mark_checked(path, problems):
    image = Path(path)
    stat = image.stat()
    sidecar = Path(str(image) + '.verification.json')
    record = dict(status='failed' if problems else 'passed', size=stat.st_size,
                  mtime_ns=stat.st_mtime_ns)
    if problems:
        record['problems'] = problems[:5]
    fd, name = tempfile.mkstemp(prefix=sidecar.name + '.', dir=sidecar.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            json.dump(record, stream, ensure_ascii=False, indent=2)
            stream.write('\n')
        os.replace(name, sidecar)
    finally:
        Path(name).unlink(missing_ok=True)


def verify_generated(path, verify, *args, **kwargs):
    try:
        problems = verify(path, *args, **kwargs)
    except (OSError, ValueError, RuntimeError) as exc:
        problems = [str(exc)]
    mark_checked(path, problems)
    return problems


def verify_written_sectors(path, sectors, samples, *, volume=False):
    """Read back representative generated bytes and check the exact output size."""
    image = Path(path)
    if sectors <= 0 or image.stat().st_size != sectors * 2048:
        return ['镜像长度与写入计划不符。 / Image size does not match the write plan.']
    problems = []
    with image.open('rb') as stream:
        if volume:
            stream.seek(16 * 2048)
            if stream.read(7) != b'\x01CD001\x01':
                problems.append('无法读回 ISO 9660 卷头。 / The ISO 9660 volume header could not be read back.')
        for lba, expected in samples:
            stream.seek(lba * 2048)
            if stream.read(len(expected)) != expected:
                problems.append(f'扇区 {lba} 读回不符。 / Sector {lba} does not match the generated data.')
    return problems


def require_checked(image, stat):
    """A passing self-check applies only to the version of the ISO that was checked."""
    try:
        record = json.loads(Path(str(image) + '.verification.json').read_text(encoding='utf-8'))
        if record['status'] == 'failed':
            raise ValueError('镜像未通过自检。请重新生成镜像。 / The image failed verification. Regenerate it.')
        if (record['status'], record['size'], record['mtime_ns']) == ('passed', stat.st_size, stat.st_mtime_ns):
            return
    except (OSError, KeyError, TypeError, json.JSONDecodeError):
        pass
    raise ValueError('镜像缺少当前文件的自检通过记录。请重新生成镜像。 / '
                     'Image verification is missing for this file. Regenerate the image.')


def finished_stat(image):
    try:
        info = image.stat()
        if (not S_ISREG(info.st_mode) or image.suffix.lower() != '.iso'
                or Path(str(image) + iso9660.UNFINISHED).exists()):
            raise FileNotFoundError
    except FileNotFoundError:
        raise FileNotFoundError('请选择已完成的 ISO 镜像。 / Choose a finished ISO image.') from None
    if not info.st_size or info.st_size % 2048:
        raise ValueError('ISO 大小必须是 2048 字节的正整数倍。 / ISO size must be a positive multiple of 2048 bytes.')
    return info
