import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {matches,notice,resultText,safeGithub,receive,hint} from '../discprobe/web/home/community.mjs';
const feed=JSON.parse(readFileSync(new URL('../news/community.json',import.meta.url),'utf8'));
for(const bad of ['http://github.com/a','https://github.com.evil.test/a','https://user@github.com/a','javascript:alert(1)','https://github.com/a?b=1','https://github.com/\\evil']) assert.equal(safeGithub(bad),false);
assert.equal(safeGithub('https://github.com/a/b#comment-1'),true);
const a=structuredClone(feed.entries.find(e=>e.media==='dvd'&&e.result!=='failed'));
const b=structuredClone(a); b.id='MID'; a.id='CAP';
a.disc.mid=null; a.disc.capacity_sectors=999; a.also=[];
b.disc.mid='EXACT'; b.disc.capacity_sectors=123; b.also=[];
assert.deepEqual(matches([a,b],{media:'dvd',mid:'exact',sectors:999}).map(e=>e.id),['MID','CAP']);
b.result='failed'; assert.equal(matches([b],{mid:'EXACT'}).length,0);
assert.equal(matches([b],{mid:'EXACT',includeFailed:true}).length,1);
assert.match(resultText('failed'),/有人用这组失败了/);
assert.match(notice(a),/不是 DP 测的.*没有实测范围.*这批盘还没确认/);
assert.equal(hint([a],{sectors:123}),null);
assert.equal(hint([a],{sectors:999}).rows.length,1);
let call;
const got={feed,date:feed.date,count:feed.count,from:'cache'};
assert.equal((await receive({refresh:true,fetcher:async(url,opts)=>{call={url,opts};return new Response(JSON.stringify(got));}})).from,'cache');
assert.equal(call.url,'/api/community?refresh=1'); assert.equal(call.opts.credentials,'omit'); assert.equal(call.opts.method,'GET');
await assert.rejects(receive({fetcher:async()=>new Response('{}')}),/invalid/);
await assert.rejects(receive({fetcher:async()=>new Response('x',{status:500})}),/HTTP 500/);
console.log('community matching, provenance, failed defaults and safe requests passed');
