import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source = readFileSync(new URL('../discprobe/web/home/presetio.js', import.meta.url), 'utf8');
const {request, selectedIndexes, rowSummary, init} = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
let call;
const fetcher = async (url, options) => { call = {url, options}; return {ok: true, json: async () => ({version: 1, presets: []})}; };
assert.equal((await request(fetcher)).version, 1);
assert.equal(call.url, '/api/presets');
await request(fetcher, {operation: 'import', selected: [1]});
assert.deepEqual(JSON.parse(call.options.body), {operation: 'import', selected: [1]});
assert.equal(call.options.method, 'POST');
await assert.rejects(request(async () => ({ok: false, status: 400, json: async () => ({error: 'bad file'})})), /bad file/);
const rows = [{index: 0, valid: false}, {index: 1, valid: true}, {index: 2, valid: true}];
assert.deepEqual(selectedIndexes(rows, new Set([0, 1])), [1]);
assert.deepEqual(selectedIndexes(rows, new Set()), []);
assert.match(rowSummary({media: 'cd', preset: {id: '<script>', sectors: 333001, pitchLinear: .001}}), /CD.*<script>.*333001.*0.001/);
const entry = {hidden: false};
assert.equal(await init(entry, async () => ({ok: false, status: 404, json: async () => ({error: 'not found'})})), null);
assert.equal(entry.hidden, true);
assert.equal(await init(entry, async () => { throw Error('offline'); }), null);
assert.equal(entry.hidden, true);
console.log('presetio pure logic passed');
