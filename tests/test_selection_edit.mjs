import assert from 'node:assert/strict';
import {selectionPixels,uniqueLayerName} from '../discprobe/web/home/design/selection-edit.mjs';
const layer={x:0,y:0,width:4,rot:0,w:4,h:4,px:{data:new Uint8ClampedArray(64).fill(255)}};
const g={width:4,height:4,left_mm:-2,top_mm:-2,cell_mm:1};
const bits=Uint8Array.from({length:16},(_,i)=>+(i%4<2));
const p=selectionPixels(layer,bits,g);
assert.equal(p.selected[3],255);assert.equal(p.selected[15],0);
const feather=selectionPixels(layer,bits,g,1);
assert(feather.selected.some((v,i)=>i%4===3&&v>0&&v<255));
for(let i=3;i<64;i+=4)assert.equal(feather.selected[i]+feather.remaining[i],255);
assert.equal(layer.px.data[3],255);
assert.equal(selectionPixels({...layer,x:20},bits,g).selected[3],0);
const rotated=selectionPixels({...layer,rot:90},bits,g);
assert.equal(rotated.selected[3],0);assert.equal(rotated.selected[63],255);
assert.equal(uniqueLayerName([{name:'山水'},{name:'山水 2'}],'山水.png'),'山水 3');
assert.equal(uniqueLayerName([{name:'图片 1'}],''),'图片 2');
assert.equal(uniqueLayerName([],'490268DE8.png'),'490268DE8');
assert.equal(uniqueLayerName([{name:'holiday.2026'}],'holiday.2026','Image',false),'holiday.2026 2');
console.log('selection pixels: source resolution, feather, alpha partition, rotation, bounds, names passed');
