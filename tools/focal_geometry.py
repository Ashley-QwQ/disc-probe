"""Rebuild/check the focal pose, 4096-square delta map and browser height constants offline."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
import tempfile

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from discprobe import focal as F
from discprobe.hashing import file_sha256 as sha

DATA = ROOT / 'data/focal'
WEB = ROOT / 'discprobe/web/home/design/focal-geometry.mjs'
CACHE_ENV = 'DISC_PROBE_FOCAL_CACHE_DIR'
DEFAULT_CACHE = Path('D:/dp-dev/tmp/focal/cache')


def cache_dir():
    return Path(os.environ.get(CACHE_ENV) or DEFAULT_CACHE).expanduser().resolve()


def pose_data(map_sha256):
    return dict(schema_version=2, camera=list(F.CAMERA), flash=list(F.FLASH),
                video_focal_px=F.VIDEO_FOCAL_PX, video_width_px=F.VIDEO_WIDTH_PX,
                photo_native_focal_px=F.PHOTO_FOCAL_PX, table_height_mm=F.TABLE_HEIGHT_MM,
                camera_z_mm=F.DESIGN_Z_MM, ruler_cm=F.DESIGN_RULER_CM, delta_scale=1.,
                formula='H_table_new = H_table_old * f_video_new / f_video_old; H_disc = H_table - disc - sheet',
                status='provisional-two-height-measurement-pending',
                source=dict(calibration='discprobe/focal.py', calibration_sha256=sha(ROOT/'discprobe/focal.py'),
                            legacy='data/focal/legacy.json', legacy_sha256=sha(DATA/'legacy.json')),
                delta_map=dict(file='delta_map_1x.npy', size=F.MAP_SIZE, width_mm=F.MAP_WIDTH_MM,
                               dtype='float32', byte_order='little', npy_version=[1,0],
                               axes='pixel centres; x right, y up; top left (-80,+80)',
                               annulus_mm=[24,58], outside='NaN', sha256=map_sha256,
                               generator='tools/focal_geometry.py',
                               cache=dict(default=str(DEFAULT_CACHE), environment=CACHE_ENV)))


def web_text():
    return ('// Generated by tools/focal_geometry.py from discprobe/focal.py; do not calibrate here.\n'
            + f'export const DESIGN_Z_MM = {F.DESIGN_Z_MM!r};\n'
            + f'export const DESIGN_RULER_CM = {F.DESIGN_RULER_CM!r};\n'
            + f'export const DISC_AND_SHEET_MM = {F.DISC_AND_SHEET_MM!r};\n')


def generate_map(path):
    d = np.lib.format.open_memmap(path, mode='w+', dtype='<f4',
                                shape=(F.MAP_SIZE,F.MAP_SIZE), version=(1,0))
    for start in range(0,F.MAP_SIZE,128):
        stop=min(start+128,F.MAP_SIZE)
        d[start:stop]=F.map_rows(start,stop,size=F.MAP_SIZE)
    d.flush()
    del d
    return sha(path)


def build(check=False):
    cache = cache_dir()
    cache.mkdir(parents=True, exist_ok=True)
    # Check a fresh regeneration, never trust a pre-existing cached map. A
    # temporary file also keeps interrupted builds from leaving a partial cache.
    with tempfile.TemporaryDirectory(prefix='focal-', dir=cache) as work:
        generated = Path(work)/'delta_map_1x.npy'
        digest = generate_map(generated)
        if not check:
            generated.replace(cache/'delta_map_1x.npy')
    pose = json.dumps(pose_data(digest), indent=2)+'\n'
    for path,text in [(DATA/'pose_1x.json',pose),(WEB,web_text())]:
        if check:
            assert path.read_text(encoding='utf-8')==text, f'{path.name} differs'
        else:
            path.write_text(text,encoding='utf-8')
    print('focal geometry matches' if check else 'focal geometry regenerated',
          f'f={F.VIDEO_FOCAL_PX} px, table={F.TABLE_HEIGHT_MM:.6f} mm, disc={F.DESIGN_Z_MM:.6f} mm')


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check',action='store_true')
    build(ap.parse_args().check)
