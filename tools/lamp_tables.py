"""Write the lamp view's tables for the browser: the A3 v3 texture curves and the constants of simulate_a3.

    python tools/lamp_tables.py            # writes discprobe/web/home/design/lamp-a3v3.{bin,json}
    python tools/lamp_tables.py --check    # recomputes and compares, writes nothing

The browser renders the lamp view itself (design/lamp-optics.mjs, a port of discprobe.simulate_a3.render), so it
needs the same table: every texture's XYZ against the along-track factor (float32, specs x delta x 3, little
endian), the CIE matching functions for the grooves' rainbow, XYZ -> linear sRGB and the model's constants.
Nothing here is new data: the .bin is simulate_a3v3.npz's xyz array byte for byte.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from discprobe import simulate, simulate_a3  # noqa: E402

OUT = ROOT / "discprobe/web/home/design"
CONSTANTS = ["A5_PERIOD_UM", "PITCH_UM", "TEX_GAIN", "DESATURATE", "VEIL", "VEIL_RGB", "GLARE_GAIN", "RAINBOW_GAIN",
             "ZERO_ORDER_DARK", "OTHER_DARK"]


def build():
    with np.load(simulate_a3.TABLE, allow_pickle=False) as z:
        specs = [str(s) for s in z["specs"]]
        delta, xyz = z["delta"], z["xyz"]
        data = np.ascontiguousarray(xyz, dtype="<f4").tobytes()
        meta = dict(
            note="generated by tools/lamp_tables.py from discprobe/simulate_a3v3.npz; do not edit",
            table_sha256=hashlib.sha256(simulate_a3.TABLE.read_bytes()).hexdigest(),
            signature=str(z["signature"]), source=str(z["source"]), lamp=str(z["lamp"]),
            bin_sha256=hashlib.sha256(data).hexdigest(),
            specs=specs,
            delta=dict(first=float(delta[0]), last=float(delta[-1]), n=int(len(delta))),
            cmf=dict(first_nm=float(z["cmf_nm"][0]), last_nm=float(z["cmf_nm"][-1]), n=int(len(z["cmf_nm"])),
                     values=[round(float(v), 9) for v in z["cmf"].astype(float).ravel()]),
            xyz_to_srgb=[round(float(v), 9) for v in z["xyz_to_srgb"].astype(float).ravel()],
            constants={k: getattr(simulate_a3, k) for k in CONSTANTS} | dict(HUB_MM=simulate.HUB_MM, EDGE_MM=simulate.EDGE_MM,
                                                                              FINE_SAMPLES=simulate.FINE_SAMPLES),
        )
    for k in ("first", "last"):
        meta["delta"][k] = round(meta["delta"][k], 9)
    meta["constants"]["VEIL_RGB"] = list(meta["constants"]["VEIL_RGB"])
    return data, json.dumps(meta, indent=1, ensure_ascii=False) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    data, meta = build()
    targets = [(OUT / "lamp-a3v3.bin", data), (OUT / "lamp-a3v3.json", meta.encode("utf8"))]
    if a.check:
        # a checkout may turn the .json's line ends into CRLF (core.autocrlf); the bytes that matter are the same
        def same(path, content):
            data = path.read_bytes() if path.exists() else None
            return data is not None and (data if path.suffix == ".bin" else data.replace(b"\r\n", b"\n")) == content
        stale = [str(path.relative_to(ROOT)) for path, content in targets if not same(path, content)]
        print("stale: " + ", ".join(stale) if stale else "lamp tables up to date")
        return 1 if stale else 0
    for path, content in targets:
        path.write_bytes(content)
        print(f"wrote {path.relative_to(ROOT)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
